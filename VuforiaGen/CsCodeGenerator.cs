using CppAst;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace VuforiaGen
{
	public class CsCodeGenerator
	{
		public static readonly CsCodeGenerator Instance = new CsCodeGenerator();

		private const string NativeClass = "Vuforia";
		private const string DllImportName = "VuforiaEngine";

		public void Generate(List<CppCompilation> compilations, string outputPath)
		{
			// Merge all compilations, deduplicating by name
			var allEnums = new List<CppEnum>();
			var allClasses = new List<CppClass>();
			var allFunctions = new List<CppFunction>();
			var allTypedefs = new List<CppTypedef>();
			var allMacros = new List<CppMacro>();

			var seenEnums = new HashSet<string>();
			var seenClasses = new HashSet<string>();
			var seenFunctions = new HashSet<string>();
			var seenTypedefs = new HashSet<string>();
			var seenMacros = new HashSet<string>();

			int anonymousEnumId = 0;
			var seenAnonymousItems = new HashSet<string>();
			foreach (var compilation in compilations)
			{
				foreach (var e in compilation.Enums)
				{
					if (e.IsAnonymous)
					{
						// For anonymous enums, deduplicate by individual item names
						bool hasNewItems = false;
						foreach (var item in e.Items)
						{
							if (!seenAnonymousItems.Contains(item.Name))
								hasNewItems = true;
						}

						if (hasNewItems)
						{
							foreach (var item in e.Items)
								seenAnonymousItems.Add(item.Name);

							var key = $"__anon_{anonymousEnumId++}";
							allEnums.Add(e);
						}
					}
					else
					{
						if (seenEnums.Add(e.Name))
							allEnums.Add(e);
					}
				}

				foreach (var c in compilation.Classes)
				{
					var key = c.Name ?? "";
					if (seenClasses.Add(key))
						allClasses.Add(c);
				}

				foreach (var f in compilation.Functions)
				{
					if (seenFunctions.Add(f.Name))
						allFunctions.Add(f);
				}

				foreach (var t in compilation.Typedefs)
				{
					if (seenTypedefs.Add(t.Name))
						allTypedefs.Add(t);
				}

				foreach (var m in compilation.Macros)
				{
					if (seenMacros.Add(m.Name))
						allMacros.Add(m);
				}
			}

			// Pre-collect typedef lists for opaque handle detection
			Helpers.TypedefList = allTypedefs
				.Where(t => Helpers.IsOpaqueType(t))
				.Select(t => t.Name).ToList();

			// Pre-collect delegate type names
			Helpers.DelegateTypes = allTypedefs
				.Where(t => Helpers.IsFunctionPointerTypedef(t))
				.Select(t => t.Name)
				.ToHashSet();

			Console.WriteLine($"Found {allEnums.Count} enums (merged)");
			Console.WriteLine($"Found {allClasses.Count} classes/structs (merged)");
			Console.WriteLine($"Found {allFunctions.Count} functions (merged)");
			Console.WriteLine($"Found {allTypedefs.Count} typedefs (merged)");
			Console.WriteLine($"Found {allMacros.Count} macros (merged)");
			Console.WriteLine($"Found {Helpers.TypedefList.Count} opaque handles");

			// Generate each file
			GenerateConstants(allEnums, allMacros, outputPath);
			GenerateEnums(allEnums, allTypedefs, outputPath);
			GenerateDelegates(allTypedefs, outputPath);
			GenerateStructs(allClasses, outputPath);
			GenerateFunctions(allFunctions, outputPath);
			GenerateHandles(allTypedefs, outputPath);
		}

		private void GenerateConstants(List<CppEnum> enums, List<CppMacro> macros, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Constants.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine("using System;");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");
			writer.WriteLine($"\tpublic static partial class {NativeClass}");
			writer.WriteLine("\t{");

			// VU_CONST_INT values from enums (anonymous enums used as constants)
			var seenConstantNames = new HashSet<string>();
			foreach (var enumDef in enums)
			{
				if (!enumDef.IsAnonymous)
					continue;

				foreach (var item in enumDef.Items)
				{
					// Only include Vuforia constants
					if (!item.Name.StartsWith("VU_"))
						continue;

					// Skip duplicates from multi-platform parsing
					if (!seenConstantNames.Add(item.Name))
						continue;

					var csName = Helpers.StripPrefix(item.Name);
					Helpers.PrintComments(writer, item.Comment, "\t\t");
					writer.WriteLine($"\t\tpublic const int {csName} = {item.Value};");
					writer.WriteLine();
				}
			}

			// Macros as constants
			foreach (var macro in macros)
			{
				if (string.IsNullOrWhiteSpace(macro.Value))
					continue;

				// Only include VU_ prefixed macros
				if (!macro.Name.StartsWith("VU_"))
					continue;

				// Skip function-like macros and internal ones
				if (macro.Name.StartsWith("_") && macro.Name.EndsWith("_"))
					continue;

				// Skip complex macros with operators or function calls
				if (macro.Value.Contains("(") || macro.Value.Contains("|") || macro.Value.Contains("<<"))
					continue;

				var csMacroName = Helpers.StripPrefix(macro.Name);

				// Try to detect type
				if (int.TryParse(macro.Value, out int intVal))
				{
					writer.WriteLine($"\t\tpublic const int {csMacroName} = {macro.Value};");
					writer.WriteLine();
				}
				else if (macro.Value.StartsWith("0x") && int.TryParse(macro.Value.Substring(2), System.Globalization.NumberStyles.HexNumber, null, out _))
				{
					writer.WriteLine($"\t\tpublic const int {csMacroName} = {macro.Value};");
					writer.WriteLine();
				}
			}

			writer.WriteLine("\t}");
			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private void GenerateEnums(List<CppEnum> enums, List<CppTypedef> typedefs, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Enums.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");

			// Build a set of Flags typedef names
			var flagsTypedefs = typedefs
				.Where(t => t.Name.Contains("Flags"))
				.Select(t => t.Name.Replace("Flags", ""))
				.ToHashSet();

			foreach (var enumDef in enums)
			{
				if (enumDef.Items.Count == 0 || enumDef.IsAnonymous)
					continue;

				// Skip non-Vuforia enums (from system headers)
				if (!string.IsNullOrEmpty(enumDef.Name) && !enumDef.Name.StartsWith("Vu"))
					continue;

				Helpers.PrintComments(writer, enumDef.Comment, "\t");

				// Check if this is a flags enum
				bool isFlags = flagsTypedefs.Contains(enumDef.Name);
				if (isFlags)
				{
					writer.WriteLine("\t[System.Flags]");
				}

				var csEnumName = Helpers.StripPrefix(enumDef.Name);
				writer.WriteLine($"\tpublic enum {csEnumName} : int");
				writer.WriteLine("\t{");

				// Find common prefix for enum values and convert to PascalCase
				var valueNames = enumDef.Items.Select(i => i.Name).ToList();
				var commonPrefix = Helpers.FindCommonPrefix(valueNames);

				foreach (var item in enumDef.Items)
				{
					Helpers.PrintComments(writer, item.Comment, "\t\t");
					var strippedValue = item.Name;
					if (!string.IsNullOrEmpty(commonPrefix) && strippedValue.StartsWith(commonPrefix))
						strippedValue = strippedValue.Substring(commonPrefix.Length);
					var csValueName = Helpers.ScreamingToPascalCase(strippedValue);
					writer.WriteLine($"\t\t{csValueName} = {item.Value},");
				}

				writer.WriteLine("\t}");
				writer.WriteLine();
			}

			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private void GenerateDelegates(List<CppTypedef> typedefs, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Delegates.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine("using System;");
			writer.WriteLine("using System.Runtime.InteropServices;");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");

			foreach (var typedef in typedefs)
			{
				if (!Helpers.IsFunctionPointerTypedef(typedef))
					continue;

				CppFunctionType funcType = null;
				if (typedef.ElementType is CppPointerType ptrType && ptrType.ElementType is CppFunctionType ft)
				{
					funcType = ft;
				}
				else if (typedef.ElementType is CppFunctionType directFt)
				{
					funcType = directFt;
				}

				if (funcType == null)
					continue;

				Helpers.PrintComments(writer, typedef.Comment, "\t");

				var returnType = Helpers.ConvertToCSharpType(funcType.ReturnType);

				var parameters = new List<string>();
				foreach (var param in funcType.Parameters)
				{
					var paramType = Helpers.ConvertToCSharpType(param.Type);
					var paramName = Helpers.EscapeReservedKeyword(string.IsNullOrEmpty(param.Name) ? $"arg{parameters.Count}" : param.Name);

					// For delegate parameters, use string for const char*
					if (param.Type is CppPointerType paramPtrType && Helpers.IsCharPointer(paramPtrType))
					{
						// For const char* in callbacks, keep as byte* (unsafe)
					}

					parameters.Add($"{paramType} {paramName}");
				}

				var csDelegateName = Helpers.StripPrefix(typedef.Name);
				writer.WriteLine($"\t[UnmanagedFunctionPointer(CallingConvention.StdCall)]");
				writer.WriteLine($"\tpublic unsafe delegate {returnType} {csDelegateName}({string.Join(", ", parameters)});");
				writer.WriteLine();
			}

			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private void GenerateStructs(List<CppClass> classes, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Structs.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine("using System;");
			writer.WriteLine("using System.Runtime.InteropServices;");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");

			foreach (var classDef in classes)
			{
				if (classDef.ClassKind != CppClassKind.Struct)
					continue;

				if (!classDef.IsDefinition)
					continue;

				// Skip anonymous structs and forward declarations
				if (string.IsNullOrEmpty(classDef.Name))
					continue;

				// Skip opaque type forward declarations (names ending with _)
				if (classDef.Name.EndsWith("_"))
					continue;

				// Skip non-Vuforia structs (from system headers)
				if (!classDef.Name.StartsWith("Vu"))
					continue;

				bool isUnion = classDef.ClassKind == CppClassKind.Union;

				Helpers.PrintComments(writer, classDef.Comment, "\t");

				if (isUnion)
				{
					writer.WriteLine("\t[StructLayout(LayoutKind.Explicit)]");
				}
				else
				{
					writer.WriteLine("\t[StructLayout(LayoutKind.Sequential)]");
				}

				var csStructName = Helpers.StripPrefix(classDef.Name);
				writer.WriteLine($"\tpublic unsafe partial struct {csStructName}");
				writer.WriteLine("\t{");

				foreach (var field in classDef.Fields)
				{
					if (isUnion)
					{
						writer.WriteLine("\t\t[FieldOffset(0)]");
					}

					Helpers.PrintComments(writer, field.Comment, "\t\t");

					var fieldType = Helpers.ConvertToCSharpType(field.Type);
					var fieldName = Helpers.EscapeReservedKeyword(Helpers.PascalCaseField(field.Name));

					// Handle fixed-size arrays
					if (field.Type is CppArrayType arrayType && arrayType.Size > 0)
					{
						var elementType = Helpers.ConvertToCSharpType(arrayType.ElementType);

						// Fixed-size arrays for primitive types
						if (IsPrimitiveFixedType(elementType))
						{
							writer.WriteLine($"\t\tpublic fixed {elementType} {fieldName}[{arrayType.Size}];");
						}
						else
						{
							// For non-primitive fixed arrays, emit individual fields
							for (int i = 0; i < arrayType.Size; i++)
							{
								writer.WriteLine($"\t\tpublic {elementType} {fieldName}_{i};");
							}
						}
					}
					else if (field.Type is CppPointerType ptrType && Helpers.IsCharPointer(ptrType))
					{
						// const char* fields → byte*
						writer.WriteLine($"\t\tpublic byte* {fieldName};");
					}
					else
					{
						// Check if this is a pointer to a delegate type → IntPtr
						if (field.Type is CppPointerType fieldPtrType
							&& fieldPtrType.ElementType is CppTypedef fieldTd
							&& Helpers.DelegateTypes.Contains(fieldTd.Name))
						{
							writer.WriteLine($"\t\tpublic IntPtr {fieldName};");
						}
						else
						{
							// Regular field
							writer.WriteLine($"\t\tpublic {fieldType} {fieldName};");
						}
					}
				}

				writer.WriteLine("\t}");
				writer.WriteLine();
			}

			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private void GenerateFunctions(List<CppFunction> functions, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Functions.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine("using System;");
			writer.WriteLine("using System.Runtime.InteropServices;");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");
			writer.WriteLine($"\tpublic static unsafe partial class {NativeClass}");
			writer.WriteLine("\t{");

			foreach (var function in functions)
			{
				// Skip inline and template functions
				if (function.Flags.HasFlag(CppFunctionFlags.Inline))
					continue;

				if (function.Flags.HasFlag(CppFunctionFlags.FunctionTemplate))
					continue;

				// Skip non-Vuforia functions (system headers leak)
				if (!function.Name.StartsWith("vu"))
					continue;

				Helpers.PrintComments(writer, function.Comment, "\t\t");

				var returnType = Helpers.ConvertToCSharpType(function.ReturnType);

				// Build parameter list
				var parameters = new List<string>();
				foreach (var param in function.Parameters)
				{
					var paramType = Helpers.ConvertToCSharpType(param.Type);
					var paramName = Helpers.EscapeReservedKeyword(string.IsNullOrEmpty(param.Name) ? $"arg{parameters.Count}" : param.Name);

					// Special handling for const char* parameters → string via marshalling
					if (param.Type is CppPointerType ptrType && Helpers.IsCharPointer(ptrType))
					{
						// Check if it's const char* (input) vs char* (output)
						bool isConst = false;
						if (param.Type is CppPointerType pt)
						{
							if (pt.ElementType is CppQualifiedType qt && qt.Qualifier == CppTypeQualifier.Const)
								isConst = true;
						}

						if (isConst)
						{
							parameters.Add($"[MarshalAs(UnmanagedType.LPStr)] string {paramName}");
							continue;
						}
					}

					// Special handling for const char** parameters → out string or byte**
					if (param.Type is CppPointerType outerPtr
						&& outerPtr.ElementType is CppPointerType innerPtr
						&& Helpers.IsCharPointer(innerPtr))
					{
						parameters.Add($"byte** {paramName}");
						continue;
					}

					// Handle delegate pointer parameters → IntPtr
					if (param.Type is CppPointerType delegatePtr
						&& delegatePtr.ElementType is CppTypedef delegateTd
						&& Helpers.DelegateTypes.Contains(delegateTd.Name))
					{
						parameters.Add($"IntPtr {paramName}");
						continue;
					}

					parameters.Add($"{paramType} {paramName}");
				}

				var csMethodName = Helpers.StripPrefix(function.Name);
				writer.WriteLine($"\t\t[DllImport(\"{DllImportName}\", EntryPoint = \"{function.Name}\", CallingConvention = CallingConvention.StdCall)]");
				writer.WriteLine($"\t\tpublic static extern {returnType} {csMethodName}({string.Join(", ", parameters)});");
				writer.WriteLine();
			}

			writer.WriteLine("\t}");
			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private void GenerateHandles(List<CppTypedef> typedefs, string outputPath)
		{
			var filePath = Path.Combine(outputPath, "Handles.cs");
			using var writer = new StreamWriter(filePath);

			writer.WriteLine("// <auto-generated/>");
			writer.WriteLine("using System;");
			writer.WriteLine();
			writer.WriteLine("namespace Evergine.Bindings.Vuforia");
			writer.WriteLine("{");

			foreach (var typedef in typedefs)
			{
				if (!Helpers.IsOpaqueType(typedef))
					continue;

				var name = Helpers.StripPrefix(typedef.Name);

				Helpers.PrintComments(writer, typedef.Comment, "\t");
				writer.WriteLine($"\tpublic partial struct {name} : IEquatable<{name}>");
				writer.WriteLine("\t{");
				writer.WriteLine($"\t\tpublic readonly IntPtr Handle;");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic {name}(IntPtr existingHandle) {{ Handle = existingHandle; }}");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic static {name} Null => new {name}(IntPtr.Zero);");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic static implicit operator {name}(IntPtr handle) => new {name}(handle);");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic static bool operator ==({name} left, {name} right) => left.Handle == right.Handle;");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic static bool operator !=({name} left, {name} right) => left.Handle != right.Handle;");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic bool Equals({name} h) => Handle == h.Handle;");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic override bool Equals(object o) => o is {name} h && Equals(h);");
				writer.WriteLine();
				writer.WriteLine($"\t\tpublic override int GetHashCode() => Handle.GetHashCode();");
				writer.WriteLine("\t}");
				writer.WriteLine();
			}

			writer.WriteLine("}");

			Console.WriteLine($"Generated: {filePath}");
		}

		private static bool IsPrimitiveFixedType(string typeName)
		{
			return typeName switch
			{
				"bool" or "byte" or "sbyte" or "short" or "ushort" or
				"int" or "uint" or "long" or "ulong" or "float" or "double" or "char" => true,
				_ => false,
			};
		}
	}
